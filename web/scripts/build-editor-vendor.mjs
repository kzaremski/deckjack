/**
 * Builds the Editor app's vendored CodeMirror: one offline ES module.
 *
 *   npm run build:editor-vendor          write the bundle
 *   npm run build:editor-vendor -- --check   exit 1 if the committed one is stale
 *
 * Why it is committed rather than built by cargo: an app's UI is files the
 * binary embeds, and the rule that there is no build step for app UIs is what
 * lets a binary copied onto a machine serve its own UI. Building it from
 * `cargo build` would put Node on the path of every Rust build, including on
 * a machine that never touches the web side. So the output is checked in,
 * the inputs are pinned in package-lock.json, and a test rebuilds it and
 * compares, which keeps the two from drifting.
 *
 * esbuild comes with Vite, so this adds no tool.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
export const ENTRY = resolve(here, "codemirror-entry.js");
export const OUTPUT = resolve(here, "../../crates/deckjack-editor/ui/vendor/codemirror.js");

const BANNER =
  "/* CodeMirror 6 for the Deckjack editor. Generated by web/scripts/build-editor-vendor.mjs from\n" +
  "   web/scripts/codemirror-entry.js; do not edit. CodeMirror and Lezer are MIT-licensed\n" +
  "   (c) Marijn Haverbeke and others: https://codemirror.net */";

/** The bundle's text, built in memory. */
export async function bundle() {
  return (await bundleWithImports()).text;
}

/**
 * The bundle and what it still imports, which must be nothing: an import
 * left in it would be resolved by the browser at runtime, against the app's
 * URL, and fail offline.
 */
export async function bundleWithImports() {
  const result = await build({
    metafile: true,
    entryPoints: [ENTRY],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
    write: false,
    banner: { js: BANNER },
    logLevel: "silent",
  });
  const imports = Object.values(result.metafile.outputs).flatMap((o) => o.imports);
  return { text: result.outputFiles[0].text, imports };
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const text = await bundle();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8");
    } catch {
      // Missing is stale.
    }
    if (current !== text) {
      console.error(`${OUTPUT} is stale; run npm run build:editor-vendor`);
      process.exit(1);
    }
    console.log("the vendored editor bundle is current");
  } else {
    writeFileSync(OUTPUT, text);
    console.log(`wrote ${OUTPUT} (${Math.round(text.length / 1024)} KB)`);
  }
}
